import type { Claim, EvidenceStatus, Procedure, ProcedureContentStatus, TargetTissue } from '../types';

let seq = 0;
const claim = (
  pid: string,
  textJa: string,
  sourceIds: string[],
  status: EvidenceStatus,
  limitationsJa = '',
): Claim => ({ id: `${pid}-c${++seq}`, textJa, sourceIds, status, limitationsJa });

type Def = {
  id: string;
  nameJa: string;
  genericNameJa: string;
  brandExampleJa?: string;
  aliases?: string[];
  category: string;
  regions: string[];
  targetTissues: TargetTissue[];
  mechanism: [string, string[], EvidenceStatus, string?];
  expected: [string, string[], EvidenceStatus, string?][];
  limits: [string, string[], EvidenceStatus, string?][];
  temp: [string, string[], EvidenceStatus, string?][];
  complications: [string, string[], EvidenceStatus, string?][];
  reversibility: [string, string[], EvidenceStatus, string?];
  evaluationTimingJa: string;
  durabilityJa: string;
  recoveryCardIds: string[];
  doseReferenceIds?: string[];
  priceExampleIds?: string[];
  contentStatus: ProcedureContentStatus;
};

const build = (d: Def): Procedure => {
  const mk = (t: [string, string[], EvidenceStatus, string?]) => claim(d.id, t[0], t[1], t[2], t[3] ?? '');
  return {
    id: d.id,
    nameJa: d.nameJa,
    genericNameJa: d.genericNameJa,
    brandExampleJa: d.brandExampleJa ?? '（製品名は個別確認）',
    aliases: d.aliases ?? [],
    category: groupOf(d.id),
    regions: d.regions,
    targetTissues: d.targetTissues,
    mechanism: mk(d.mechanism),
    expectedChanges: d.expected.map(mk),
    limitations: d.limits.map(mk),
    temporaryReactions: d.temp.map(mk),
    importantComplications: d.complications.map(mk),
    reversibility: mk(d.reversibility),
    evaluationTimingJa: d.evaluationTimingJa,
    durabilityJa: d.durabilityJa,
    recoveryCardIds: d.recoveryCardIds,
    doseReferenceIds: d.doseReferenceIds ?? [],
    priceExampleIds: d.priceExampleIds ?? [],
    contentStatus: d.contentStatus,
    independentlyReviewedByClinician: false,
  };
};

const groupOf = (id: string): string => {
  const n = Number(id.slice(1));
  if (n <= 18) return '注入・筋肉・脂肪';
  if (n <= 23) return '引き締め・引き上げ';
  if (n <= 31) return '目元';
  if (n <= 44) return '鼻・骨格・口元';
  return '肌';
};

